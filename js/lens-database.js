export function getLens(id) {
    return lenses.find(l => l.id === id) || lenses[0];
}

export function getLensByType(type) {
    return lenses.filter(l => l.type === type);
}

export function nearestFocalLength(lens, target) {
    let best = lens.focalLengths[0];
    let bestDist = Math.abs(target - best);
    for (let i = 1; i < lens.focalLengths.length; i++) {
        const d = Math.abs(target - lens.focalLengths[i]);
        if (d < bestDist) {
            bestDist = d;
            best = lens.focalLengths[i];
        }
    }
    return best;
}
